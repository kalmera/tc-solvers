"""Mark generated OCaml sources and normalize their comments and whitespace."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
header = '(* GENERATED by make regenerate; do not edit. See docs/third-party.md. *)\n'
for directory in ('ocaml/extracted', 'ocaml/adapters/goblint/generated', 'ocaml/library/generated'):
    for path in sorted((root / directory).iterdir()):
        if path.suffix in ('.ml', '.mli'):
            content = path.read_text()
            marked = content if content.startswith(header) else header + content
            # Extraction emits documentation comments, including unattached ones.
            marked = marked.replace('(**', '(*')
            marked = '\n'.join(line.rstrip(' \t') for line in marked.split('\n'))
            if marked != content:
                path.write_text(marked)
