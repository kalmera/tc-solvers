"""Mark reproducible generated OCaml sources without changing their code."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
header = '(* GENERATED by make regenerate; do not edit. See docs/third-party.md. *)\n'
for directory in ('ocaml/extracted', 'ocaml/adapters/goblint/generated', 'ocaml/library/generated'):
    for path in sorted((root / directory).iterdir()):
        if path.suffix in ('.ml', '.mli'):
            content = path.read_text()
            if not content.startswith(header):
                path.write_text(header + content)
