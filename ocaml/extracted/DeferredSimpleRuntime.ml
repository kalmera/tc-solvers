  | KAfterSide (h, r, c0) -> f3 h r c0 (continuation_rec f f0 f1 f2 f3 f4 c0)
  | KAfterSpawn (h, r, c0) -> f4 h r c0 (continuation_rec f f0 f1 f2 f3 f4 c0)

  (* val continue : continuation -> control **)

  let continue = function
  | KLoop -> RunLoop
  | KSeedLoop remaining -> RunSeedLoop remaining
  | KSolveOneLoop (owner, rest) -> RunSolveOneLoop (owner, rest)
  | KAfterGet (owner, target, next, rest) ->
    AfterGet (owner, target, next, rest)
  | KAfterSide (owner, next, rest) -> AfterSide (owner, next, rest)
  | KAfterSpawn (owner, next, rest) -> AfterSpawn (owner, next, rest)

  type config = { cfg_state : state; cfg_control : control }

  (* val cfg_state : config -> state **)

  let cfg_state c =
    c.cfg_state

  (* val cfg_control : config -> control **)

  let cfg_control c =
    c.cfg_control

  (* val initial_config : V.t list -> config **)

  let initial_config initial =
    { cfg_state = empty_state; cfg_control = (RunSeeds initial) }

  (* val next_config : ConstraintSystem.system -> config -> config option **)

  let next_config tf c =
    let st = c.cfg_state in
    (match c.cfg_control with
     | RunLoop ->
       (match queue_pop st.queue with
        | Some p ->
          let (owner, rest) = p in
          Some { cfg_state = (with_queue st rest); cfg_control = (RunSolveOne
          (owner, KLoop)) }
        | None ->
          (match st.pending_spawns with
           | [] -> None
           | target :: rest ->
             Some { cfg_state = (with_spawns st rest st.requested_spawns);
               cfg_control = (RunSeeds (target :: [])) }))
     | RunSeeds roots ->
       (match roots with
        | [] -> Some { cfg_state = st; cfg_control = RunLoop }
        | root :: remaining ->
          if (||) (S.mem root st.started) (is_dormant st root)
          then Some { cfg_state = st; cfg_control = (RunSeeds remaining) }
          else (match Ranking.lookup st.ranking root with
                | Some _ ->
                  let (st1, owner) = observe st root in
                  Some { cfg_state = st1; cfg_control = (RunSolveOne (owner,
                  (KSeedLoop remaining))) }
                | None ->
                  if (&&) (pure_bottom_rhs tf root)
                       (negb (is_materialized st root))
                  then Some { cfg_state = (remember_dormant st root);
                         cfg_control = (RunSeeds remaining) }
                  else let (st1, owner) = observe st root in
                       Some { cfg_state = st1; cfg_control = (RunSolveOne
                       (owner, (KSeedLoop remaining))) }))
     | RunSeedLoop remaining ->
       (match queue_pop st.queue with
        | Some p ->
          let (owner, rest) = p in
          Some { cfg_state = (with_queue st rest); cfg_control = (RunSolveOne
          (owner, (KSeedLoop remaining))) }
        | None -> Some { cfg_state = st; cfg_control = (RunSeeds remaining) })
     | RunSolveOne (owner, k) ->
       let variable = owner.handle_variable in
       let st1 = start_evaluation st variable in
       Some { cfg_state = (with_started st1 (S.add variable st1.started));
       cfg_control = (RunRhs (owner, (tf variable), k)) }
     | RunSolveOneLoop (owner, k) ->
       if owner_may_still_be_queued st owner
       then (match queue_pop st.queue with
             | Some p ->
               let (next, rest) = p in
               if V.eq_dec next.handle_variable owner.handle_variable
               then Some { cfg_state = (with_queue st rest); cfg_control =
                      (RunSolveOne (owner, k)) }
               else Some { cfg_state = (with_queue st rest); cfg_control =
                      (RunSolveOne (next, (KSolveOneLoop (owner, k)))) }
             | None -> None)
       else if D.leq (aggregate st owner.handle_variable)
                 (sigma_value st owner.handle_variable)
            then Some { cfg_state = st; cfg_control = (continue k) }
            else None
     | RunRhs (owner, body, k) ->
       let owner_variable = owner.handle_variable in
       (match body with
        | ConstraintSystem.Ret direct ->
          Some { cfg_state = (set_value st owner_variable direct);
            cfg_control = (RunSolveOneLoop (owner, k)) }
        | ConstraintSystem.Get (target, next) ->
          if is_dormant st target
          then let st1 = add_reader st target owner_variable in
               Some { cfg_state = st1; cfg_control = (RunRhs (owner,
               (next D.bottom), k)) }
          else (match Ranking.lookup st.ranking target with
                | Some _ ->
                  let (st0, target_handle) = observe st target in
                  if is_materialized st0 target
                  then let st1 =
                         dirty_get_ready_state tf st0 owner target_handle
                       in
                       Some { cfg_state = st1; cfg_control = (RunRhs (owner,
                       (next (sigma_value st1 target)), k)) }
                  else if ltb owner.handle_rank target_handle.handle_rank
                       then Some { cfg_state = st0; cfg_control =
                              (RunSolveOne (target_handle, (KAfterGet (owner,
                              target_handle, next, k)))) }
                       else let st1 =
                              get_ready_state
                                (enqueue_handle st0 target_handle) owner
                                target_handle
                            in
                            Some { cfg_state = st1; cfg_control = (RunRhs
                            (owner, (next (sigma_value st1 target)), k)) }
                | None ->
                  if (&&) (pure_bottom_rhs tf target)
                       (negb (is_materialized st target))
                  then let st1 = remember_dormant st target in
                       let st2 = add_reader st1 target owner_variable in
                       Some { cfg_state = st2; cfg_control = (RunRhs (owner,
                       (next D.bottom), k)) }
                  else let (st0, target_handle) = observe st target in
                       if ltb owner.handle_rank target_handle.handle_rank
                       then Some { cfg_state = st0; cfg_control =
                              (RunSolveOne (target_handle, (KAfterGet (owner,
                              target_handle, next, k)))) }
                       else let st1 =
                              get_ready_state
                                (enqueue_handle st0 target_handle) owner
                                target_handle
                            in
                            Some { cfg_state = st1; cfg_control = (RunRhs
                            (owner, (next (sigma_value st1 target)), k)) })
        | ConstraintSystem.Side (target, raw, next) ->
          let was_dormant = is_dormant st target in
          let (st0, target_handle) = observe st target in
          let st1 = side_ready_state st0 owner target_handle raw in
          let changed = aggregate_grew st0 st1 target in
          if was_dormant
          then if (&&) (ltb owner.handle_rank target_handle.handle_rank)
                    (negb (is_materialized st0 target))
               then Some { cfg_state = st1; cfg_control = (RunSolveOne
                      (target_handle, (KAfterSide (owner, next, k)))) }
               else Some { cfg_state = (enqueue_handle st1 target_handle);
                      cfg_control = (RunRhs (owner, next, k)) }
          else if changed
               then let st2 = mark_side_dirty st1 target in
                    if (&&) (ltb owner.handle_rank target_handle.handle_rank)
                         (negb (is_materialized st0 target))
                    then Some { cfg_state = st2; cfg_control = (RunSolveOne
                           (target_handle, (KAfterSide (owner, next, k)))) }
                    else Some { cfg_state =
                           (enqueue_handle st2 target_handle); cfg_control =
                           (RunRhs (owner, next, k)) }
               else Some { cfg_state = st1; cfg_control = (RunRhs (owner,
                      next, k)) }
        | ConstraintSystem.Spawn (target, next) ->
          if Features.defer_spawns
          then Some { cfg_state = (request_spawn st target); cfg_control =
                 (RunRhs (owner, next, k)) }
          else if is_dormant st target
               then Some { cfg_state = st; cfg_control = (RunRhs (owner,
                      next, k)) }
               else (match Ranking.lookup st.ranking target with
                     | Some _ ->
                       let (st0, target_handle) = observe st target in
                       if is_materialized st0 target
                       then Some { cfg_state = st0; cfg_control = (RunRhs
                              (owner, next, k)) }
                       else if ltb owner.handle_rank target_handle.handle_rank
                            then Some { cfg_state = st0; cfg_control =
                                   (RunSolveOne (target_handle, (KAfterSpawn
                                   (owner, next, k)))) }
                            else Some { cfg_state =
                                   (materialize
                                     (enqueue_handle st0 target_handle)
                                     target);
                                   cfg_control = (RunRhs (owner, next, k)) }
                     | None ->
                       if (&&) (pure_bottom_rhs tf target)
                            (negb (is_materialized st target))
                       then Some { cfg_state = (remember_dormant st target);
                              cfg_control = (RunRhs (owner, next, k)) }
                       else let (st0, target_handle) = observe st target in
                            if ltb owner.handle_rank target_handle.handle_rank
                            then Some { cfg_state = st0; cfg_control =
                                   (RunSolveOne (target_handle, (KAfterSpawn
                                   (owner, next, k)))) }
                            else Some { cfg_state =
                                   (materialize
                                     (enqueue_handle st0 target_handle)
                                     target);
                                   cfg_control = (RunRhs (owner, next, k)) }))
     | AfterGet (owner, target, next, k) ->
       let target_variable = target.handle_variable in
       if is_materialized st target_variable
       then let st1 = get_ready_state st owner target in
            Some { cfg_state = st1; cfg_control = (RunRhs (owner,
            (next (sigma_value st1 target_variable)), k)) }
       else None
     | AfterSide (owner, next, k) ->
       Some { cfg_state = st; cfg_control = (RunRhs (owner, next, k)) }
     | AfterSpawn (owner, next, k) ->
       Some { cfg_state = st; cfg_control = (RunRhs (owner, next, k)) })

  (* val run_fuel : int -> ConstraintSystem.system -> config -> config **)

  let rec run_fuel fuel tf c =
    (fun fO fS n -> if n=0 then fO () else fS (n-1))
      (fun _ -> c)
      (fun rest ->
      match next_config tf c with
      | Some next -> run_fuel rest tf next
      | None -> c)
      fuel

  (* val terminal_state : config -> state option **)

  let terminal_state c =
    match c.cfg_control with
    | RunLoop ->
      (match queue_peek c.cfg_state.queue with
       | Some _ -> None
       | None ->
         (match c.cfg_state.pending_spawns with
          | [] -> Some c.cfg_state
          | _ :: _ -> None))
    | _ -> None

  (* val solve_fuel :
      int -> ConstraintSystem.system -> V.t list -> state option **)

  let solve_fuel fuel tf initial =
    terminal_state (run_fuel fuel tf (initial_config initial))

  (* val solve_values_fuel :
      int -> ConstraintSystem.system -> V.t list -> store option **)

  let solve_values_fuel fuel tf initial =
    match solve_fuel fuel tf initial with
    | Some final -> Some final.sigma
    | None -> None
 end

