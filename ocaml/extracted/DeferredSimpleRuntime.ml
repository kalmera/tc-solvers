    let candidate = D.join direct (aggregate st owner) in
    let old = sigma_value st owner in
    if equivalent candidate old
    then st
    else if S.mem owner st.controlled
         then let updated =
                U.update false owner (stored_phase st owner) old candidate
              in
              let st1 =
                with_phases st (M.update st.phases owner (fst updated))
              in
              if equivalent (snd updated) old
              then st1
              else write_changed_value st1 owner (snd updated)
         else write_changed_value st owner candidate

  (* val owner_may_still_be_queued : state -> handle -> bool **)

  let owner_may_still_be_queued st owner =
    match queue_peek st.queue with
    | Some head ->
      if V.eq_dec head.handle_variable owner.handle_variable
      then true
      else ltb owner.handle_rank head.handle_rank
    | None -> false

  (* val pure_bottom_rhs : ConstraintSystem.system -> V.t -> bool **)

  let pure_bottom_rhs tf variable =
    match tf variable with
    | ConstraintSystem.Ret direct -> equivalent direct D.bottom
    | _ -> false

  (* val try_dirty_read :
      ConstraintSystem.system -> state -> handle -> handle -> state option **)

  let try_dirty_read tf st owner target =
    if V.eq_dec owner.handle_variable target.handle_variable
    then None
    else if is_side_dirty st target.handle_variable
         then (match tf target.handle_variable with
               | ConstraintSystem.Ret direct ->
                 if equivalent direct D.bottom
                 then let variable = target.handle_variable in
                      let candidate = D.join direct (aggregate st variable) in
                      let old = sigma_value st variable in
                      let st0 = with_started st (S.add variable st.started) in
                      let was_controlled = S.mem variable st0.controlled in
                      let st1 = promote_controlled st0 variable in
                      if equivalent candidate old
                      then Some (cancel_dirty_target st1 target)
                      else if was_controlled
                           then let updated =
                                  U.update false variable
                                    (stored_phase st1 variable) old candidate
                                in
                                if D.leq old (snd updated)
                                then let st2 =
                                       with_phases st1
                                         (M.update st1.phases variable
                                           (fst updated))
                                     in
                                     let st3 = cancel_dirty_target st2 target
                                     in
                                     let st4 =
                                       if equivalent (snd updated) old
                                       then st3
                                       else write_changed_value st3 variable
                                              (snd updated)
                                     in
                                     Some st4
                                else None
                           else if D.leq old candidate
                                then Some
                                       (write_changed_value
                                         (cancel_dirty_target st1 target)
                                         variable candidate)
                                else None
                 else None
               | _ -> None)
         else None

  (* val dirty_get_ready_state :
      ConstraintSystem.system -> state -> handle -> handle -> state **)

  let dirty_get_ready_state tf st owner target =
    let variable = target.handle_variable in
    let prepared = materialize (get_control_state st owner target) variable in
    let flushed =
      match try_dirty_read tf prepared owner target with
      | Some next -> next
      | None -> prepared
    in
    add_reader flushed variable owner.handle_variable

  type control =
  | RunLoop
  | RunSeeds of V.t list
  | RunSeedLoop of V.t list
  | RunSolveOne of handle * continuation
  | RunSolveOneLoop of handle * continuation
  | RunRhs of handle * ConstraintSystem.rhs * continuation
  | AfterGet of handle * handle * (D.t -> ConstraintSystem.rhs) * continuation
  | AfterSide of handle * ConstraintSystem.rhs * continuation
  | AfterSpawn of handle * ConstraintSystem.rhs * continuation
  and continuation =
  | KLoop
  | KSeedLoop of V.t list
  | KSolveOneLoop of handle * continuation
  | KAfterGet of handle * handle * (D.t -> ConstraintSystem.rhs)
     * continuation
  | KAfterSide of handle * ConstraintSystem.rhs * continuation
  | KAfterSpawn of handle * ConstraintSystem.rhs * continuation

  (* val control_rect :
      'a1 -> (V.t list -> 'a1) -> (V.t list -> 'a1) -> (handle ->
