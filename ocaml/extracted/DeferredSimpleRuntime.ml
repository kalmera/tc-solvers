  let control_rect f f0 f1 f2 f3 f4 f5 f6 f7 = function
  | RunLoop -> f
  | RunSeeds l -> f0 l
  | RunSeedLoop l -> f1 l
  | RunSolveOne (h, c0) -> f2 h c0
  | RunSolveOneLoop (h, c0) -> f3 h c0
  | RunRhs (h, r, c0) -> f4 h r c0
  | AfterGet (h, h0, r, c0) -> f5 h h0 r c0
  | AfterSide (h, r, c0) -> f6 h r c0
  | AfterSpawn (h, r, c0) -> f7 h r c0

