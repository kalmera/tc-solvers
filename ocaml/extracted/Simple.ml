  let rec continuation_rect f f0 f1 f2 f3 f4 = function
  | KLoop -> f
  | KSeedLoop l -> f0 l
  | KSolveOneLoop (h, c0) -> f1 h c0 (continuation_rect f f0 f1 f2 f3 f4 c0)
  | KAfterGet (h, h0, r, c0) ->
    f2 h h0 r c0 (continuation_rect f f0 f1 f2 f3 f4 c0)
  | KAfterSide (h, r, c0) -> f3 h r c0 (continuation_rect f f0 f1 f2 f3 f4 c0)
  | KAfterSpawn (h, r, c0) ->
    f4 h r c0 (continuation_rect f f0 f1 f2 f3 f4 c0)

  (* val continuation_rec :
      'a1 -> (V.t list -> 'a1) -> (handle -> continuation -> 'a1 -> 'a1) ->
      (handle -> handle -> (D.t -> ConstraintSystem.rhs) -> continuation ->
      'a1 -> 'a1) -> (handle -> ConstraintSystem.rhs -> continuation -> 'a1
      -> 'a1) -> (handle -> ConstraintSystem.rhs -> continuation -> 'a1 ->
