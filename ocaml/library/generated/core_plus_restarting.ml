    words avoid the allocation incurred by boxed [int64] operations. *)

let word_shift = 5
let word_bits = 1 lsl word_shift
let word_mask = word_bits - 1
let level_count = 7

type t = {
  levels : int array array;
  mutable maximum : int;
}

let create () =
