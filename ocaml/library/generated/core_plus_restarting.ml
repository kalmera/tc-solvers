    | [] -> cells
    | s :: rest ->
      let (source, target) = s in
      let fresh = default_side_cell source target in
      reset_cells rest (update_map cells source target fresh)

    let reset_registered_cells st owner =
    if Features.restart_side_phases
    then let ids = lookup_reset_ids st.reset_at_close owner in
         with_cells_and_resets st (reset_cells ids st.side_cells)
           (M.update st.reset_at_close owner [])
    else st

  type frame = { frame_owner : V.t; frame_phase : U.phase;
                 frame_local_side : D.t M.t; frame_previous_targets :
                 S.t; frame_current_targets : S.t; frame_min_scope :
                 V.t; frame_max_read : V.t option }

    let frame_owner f =
    f.frame_owner

    let frame_phase f =
    f.frame_phase

    let frame_local_side f =
    f.frame_local_side

    let frame_previous_targets f =
    f.frame_previous_targets

    let frame_current_targets f =
    f.frame_current_targets

    let frame_min_scope f =
    f.frame_min_scope

    let frame_max_read f =
    f.frame_max_read

    let fresh_frame st owner phase0 =
    { frame_owner = owner; frame_phase = phase0; frame_local_side = M.empty;
      frame_previous_targets = (lookup_set st.last_targets owner);
      frame_current_targets = S.empty; frame_min_scope = owner;
      frame_max_read = None }

    let with_frame_phase fr phase0 =
    { frame_owner = fr.frame_owner; frame_phase = phase0; frame_local_side =
      fr.frame_local_side; frame_previous_targets =
      fr.frame_previous_targets; frame_current_targets =
      fr.frame_current_targets; frame_min_scope = fr.frame_min_scope;
      frame_max_read = fr.frame_max_read }

    let with_frame_read fr minimum maximum =
    { frame_owner = fr.frame_owner; frame_phase = fr.frame_phase;
      frame_local_side = fr.frame_local_side; frame_previous_targets =
      fr.frame_previous_targets; frame_current_targets =
      fr.frame_current_targets; frame_min_scope = minimum; frame_max_read =
      maximum }

    let with_frame_side fr target input =
    { frame_owner = fr.frame_owner; frame_phase = fr.frame_phase;
      frame_local_side = (M.update fr.frame_local_side target input);
      frame_previous_targets = fr.frame_previous_targets;
      frame_current_targets = (S.add target fr.frame_current_targets);
      frame_min_scope = fr.frame_min_scope; frame_max_read =
      fr.frame_max_read }

    let promote_controlled st x =
    with_controlled st (S.add x st.controlled)

    let complete_get st fr target =
    let owner = fr.frame_owner in
    let st1 =
      if rank_lt st owner target then st else promote_controlled st target
    in
    let minimum =
      if rank_lt st target fr.frame_min_scope
      then target
      else fr.frame_min_scope
    in
    let maximum =
      match fr.frame_max_read with
      | Some previous ->
        if rank_lt st previous target then Some target else Some previous
      | None -> Some target
    in
    let fr1 = with_frame_read fr minimum maximum in
    let current_readers = lookup_set st1.readers target in
    let st2 =
      with_readers st1
        (M.update st1.readers target (S.add owner current_readers))
    in
    let st3 = materialize st2 target in ((st3, fr1), (sigma_value st3 target))

    let publish_value st variable value =
    notify (fun () -> Interfaces.Value_change {
      variable; old_value = sigma_value st variable; value });
    with_sigma st (M.update st.sigma variable value)

  let read_result fr target continuation value =
    notify (fun () -> Interfaces.Read { owner = fr.frame_owner; target; value });
    continuation value

  let write_dirty_value st target value =
    let st1 = publish_value st target value in
    let invalidated = S.elements (lookup_set st1.readers target) in
    let st2 = defer_all st1 invalidated in
    with_readers st2 (M.update st2.readers target S.empty)

    let try_dirty_read tf st owner target =
    if V.eq_dec owner target
    then None
    else if is_side_dirty st target
         then (match tf target with
               | ConstraintSystem.Ret direct ->
                 if equivalent direct D.bottom
                 then let candidate = D.join direct (aggregate st target) in
                      let old = sigma_value st target in
                      let was_controlled = S.mem target st.controlled in
                      let st0 = promote_controlled st target in
                      if equivalent candidate old
                      then Some (cancel_dirty_target st0 target)
                      else if was_controlled
                           then let updated =
                                  U.update false target
                                    (U.initial_phase false target) old
                                    candidate
                                in
                                if D.leq old (snd updated)
                                then let st1 = cancel_dirty_target st0 target
                                     in
                                     if equivalent (snd updated) old
                                     then Some st1
                                     else Some
                                            (write_dirty_value st1 target
                                              (snd updated))
                                else None
                           else if D.leq old candidate
                                then Some
                                       (write_dirty_value
                                         (cancel_dirty_target st0 target)
                                         target candidate)
                                else None
                 else None
               | _ -> None)
         else None

    let dirty_complete_get tf st fr target =
    let owner = fr.frame_owner in
    let st1 =
      if rank_lt st owner target then st else promote_controlled st target
    in
    let minimum =
      if rank_lt st target fr.frame_min_scope
      then target
      else fr.frame_min_scope
    in
    let maximum =
      match fr.frame_max_read with
      | Some previous ->
        if rank_lt st previous target then Some target else Some previous
      | None -> Some target
    in
    let fr1 = with_frame_read fr minimum maximum in
    let prepared = materialize st1 target in
    let flushed =
      match try_dirty_read tf prepared owner target with
      | Some next -> next
      | None -> prepared
    in
    let st2 = add_reader flushed target owner in
    ((st2, fr1), (sigma_value st2 target))

    let publish_dormant_target st target changed =
    let value = aggregate st target in
    let st1 = materialize st target in
    if changed
    then let invalidated = S.elements (lookup_set st1.readers target) in
         let st2 = publish_value st1 target value in
         let st3 = enqueue_all st2 invalidated in
         with_readers st3 (M.update st3.readers target S.empty)
    else st1

    let accumulated_side_input fr target raw =
    match M.lookup fr.frame_local_side target with
    | Some previous -> D.join previous raw
    | None -> raw

    let record_side_input fr target raw =
    let input = accumulated_side_input fr target raw in
    ((with_frame_side fr target input), input)

    let promote_side_target st fr target =
    let source = fr.frame_owner in
    if rank_lt st target source then st else promote_controlled st source

    let side_update st source target input =
    let cell = stored_side_cell st source target in
    let old_target_aggregate = aggregate st target in
    SU.update source target cell.side_phase
      (stored_contribution st source target) input old_target_aggregate

    let write_side_contribution st fr target input =
    let source = fr.frame_owner in
    let st1 = promote_side_target st fr target in
    let updated = side_update st1 source target input in
    let next_phase = fst updated in
    let next_contribution = snd updated in
    notify (fun () -> Interfaces.Side_update { source; target; input;
      old_value = stored_contribution st1 source target; value = next_contribution });
    let st2 =
      with_contributions st1
        (update_map st1.contributions target source next_contribution)
    in
    let st3 = register_reset st2 source target fr.frame_min_scope next_phase
    in
    let changed = aggregate_changed st1 st3 target in (st3, changed)

    let publish_targets st fr =
    with_last_targets st
      (M.update st.last_targets fr.frame_owner fr.frame_current_targets)

    let set_value st fr direct =
    let owner = fr.frame_owner in
    let candidate = D.join direct (aggregate st owner) in
    let old = sigma_value st owner in
    if equivalent candidate old
    then (st, fr)
    else let result =
           if S.mem owner st.controlled
           then U.update false owner fr.frame_phase old candidate
           else (fr.frame_phase, candidate)
         in
         let next_phase = fst result in
         let value = snd result in
         let fr1 = with_frame_phase fr next_phase in
         if equivalent value old
         then (st, fr1)
         else let st1 = publish_value st owner value in
              let invalidated = S.elements (lookup_set st1.readers owner) in
              let st2 = enqueue_all st1 invalidated in
              let st3 = with_readers st2 (M.update st2.readers owner S.empty)
              in
              let next_queue =
                if (&&) (S.mem owner st.controlled)
                     Features.recompute_controlled
                then queue_insert st3.ranking owner st3.queue
                else st3.queue
              in
              ((with_queue st3 next_queue), fr1)

    let pure_bottom_rhs tf variable =
    match tf variable with
    | ConstraintSystem.Ret direct -> equivalent direct D.bottom
    | _ -> false

  type control =
  | RunLoop
  | RunSeeds of V.t list
  | RunSeedLoop of V.t list
  | StartEpisode of V.t * continuation
  | RunRhs of frame * ConstraintSystem.rhs * continuation
  | RunDead of frame * D.t * V.t list * continuation
  | RunCommit of frame * D.t * continuation
  | RunDrain of frame * continuation
  | Return of continuation
  and continuation =
  | KLoop
  | KSeedLoop of V.t list
  | KAfterGet of frame * V.t * (D.t -> ConstraintSystem.rhs) * continuation
  | KAfterSide of frame * ConstraintSystem.rhs * continuation
  | KAfterSpawn of frame * ConstraintSystem.rhs * continuation
  | KDead of frame * D.t * V.t list * continuation
  | KDrain of frame * continuation

    let control_rect f f0 f1 f2 f3 f4 f5 f6 f7 = function
  | RunLoop -> f
  | RunSeeds l -> f0 l
  | RunSeedLoop l -> f1 l
  | StartEpisode (t0, c0) -> f2 t0 c0
  | RunRhs (f8, r, c0) -> f3 f8 r c0
  | RunDead (f8, t0, l, c0) -> f4 f8 t0 l c0
  | RunCommit (f8, t0, c0) -> f5 f8 t0 c0
  | RunDrain (f8, c0) -> f6 f8 c0
  | Return c0 -> f7 c0

    let control_rec f f0 f1 f2 f3 f4 f5 f6 f7 = function
  | RunLoop -> f
  | RunSeeds l -> f0 l
  | RunSeedLoop l -> f1 l
  | StartEpisode (t0, c0) -> f2 t0 c0
  | RunRhs (f8, r, c0) -> f3 f8 r c0
  | RunDead (f8, t0, l, c0) -> f4 f8 t0 l c0
  | RunCommit (f8, t0, c0) -> f5 f8 t0 c0
  | RunDrain (f8, c0) -> f6 f8 c0
  | Return c0 -> f7 c0

    let rec continuation_rect f f0 f1 f2 f3 f4 f5 = function
  | KLoop -> f
  | KSeedLoop l -> f0 l
  | KAfterGet (f6, t0, r, c0) ->
    f1 f6 t0 r c0 (continuation_rect f f0 f1 f2 f3 f4 f5 c0)
  | KAfterSide (f6, r, c0) ->
    f2 f6 r c0 (continuation_rect f f0 f1 f2 f3 f4 f5 c0)
  | KAfterSpawn (f6, r, c0) ->
    f3 f6 r c0 (continuation_rect f f0 f1 f2 f3 f4 f5 c0)
  | KDead (f6, t0, l, c0) ->
    f4 f6 t0 l c0 (continuation_rect f f0 f1 f2 f3 f4 f5 c0)
  | KDrain (f6, c0) -> f5 f6 c0 (continuation_rect f f0 f1 f2 f3 f4 f5 c0)

    let rec continuation_rec f f0 f1 f2 f3 f4 f5 = function
  | KLoop -> f
  | KSeedLoop l -> f0 l
  | KAfterGet (f6, t0, r, c0) ->
    f1 f6 t0 r c0 (continuation_rec f f0 f1 f2 f3 f4 f5 c0)
  | KAfterSide (f6, r, c0) ->
    f2 f6 r c0 (continuation_rec f f0 f1 f2 f3 f4 f5 c0)
  | KAfterSpawn (f6, r, c0) ->
    f3 f6 r c0 (continuation_rec f f0 f1 f2 f3 f4 f5 c0)
  | KDead (f6, t0, l, c0) ->
    f4 f6 t0 l c0 (continuation_rec f f0 f1 f2 f3 f4 f5 c0)
  | KDrain (f6, c0) -> f5 f6 c0 (continuation_rec f f0 f1 f2 f3 f4 f5 c0)

  type config = { cfg_state : state; cfg_control : control }

    let cfg_state c =
    c.cfg_state

    let cfg_control c =
    c.cfg_control

    let initial_config initial =
    { cfg_state = empty_state; cfg_control = (RunSeeds initial) }

    let continue_side st fr target next k = function
  | true ->
    if (&&) (rank_lt st fr.frame_owner target)
         (negb (is_materialized st target))
    then { cfg_state = st; cfg_control = (StartEpisode (target, (KAfterSide
           (fr, next, k)))) }
    else { cfg_state = (enqueue st target); cfg_control = (RunRhs (fr, next,
           k)) }
  | false -> { cfg_state = st; cfg_control = (RunRhs (fr, next, k)) }

    let continue_dead st fr direct target remaining k = function
  | true ->
    if (&&) (rank_lt st fr.frame_owner target)
         (negb (is_materialized st target))
    then { cfg_state = st; cfg_control = (StartEpisode (target, (KDead (fr,
           direct, remaining, k)))) }
    else { cfg_state = (enqueue st target); cfg_control = (RunDead (fr,
           direct, remaining, k)) }
  | false ->
    { cfg_state = st; cfg_control = (RunDead (fr, direct, remaining, k)) }

    let next_config tf c =
    let st = c.cfg_state in
    (match c.cfg_control with
     | RunLoop ->
       (match queue_pop st.queue with
        | Some p ->
          let (owner, rest) = p in
          Some { cfg_state = (with_queue st rest); cfg_control =
          (StartEpisode (owner, KLoop)) }
        | None ->
          (match Stdlib.Queue.take_opt st.pending_spawns with
           | None -> None
           | Some target ->
             Some { cfg_state = st;
               cfg_control = (RunSeeds (target :: [])) }))
     | RunSeeds roots ->
       (match roots with
        | [] -> Some { cfg_state = st; cfg_control = RunLoop }
        | root :: remaining ->
          if (||) (is_materialized st root) (is_dormant st root)
          then Some { cfg_state = st; cfg_control = (RunSeeds remaining) }
          else (match Ranking.lookup st.ranking root with
                | Some _ ->
                  let st1 = observe st root in
                  Some { cfg_state = st1; cfg_control = (StartEpisode (root,
                  (KSeedLoop remaining))) }
                | None ->
                  if pure_bottom_rhs tf root
                  then Some { cfg_state = (remember_dormant st root);
                         cfg_control = (RunSeeds remaining) }
                  else let st1 = observe st root in
                       Some { cfg_state = st1; cfg_control = (StartEpisode
                       (root, (KSeedLoop remaining))) }))
     | RunSeedLoop remaining ->
       (match queue_pop st.queue with
        | Some p ->
          let (owner, rest) = p in
          Some { cfg_state = (with_queue st rest); cfg_control =
          (StartEpisode (owner, (KSeedLoop remaining))) }
        | None -> Some { cfg_state = st; cfg_control = (RunSeeds remaining) })
     | StartEpisode (owner, k) ->
       let st1 = clear_side_dirty (materialize st owner) owner in
       let phase0 = U.initial_phase false owner in
       evaluation_start owner;
       Some { cfg_state = st1; cfg_control = (RunRhs
       ((fresh_frame st1 owner phase0), (tf owner), k)) }
     | RunRhs (fr, body, k) ->
       (match body with
        | ConstraintSystem.Ret direct ->
          notify (fun () -> Interfaces.Evaluation_result (fr.frame_owner, direct));
          Some { cfg_state = st; cfg_control = (RunDead (fr, direct,
            (if Features.eliminate_dead_sides
             then S.elements fr.frame_previous_targets
             else []),
            k)) }
        | ConstraintSystem.Get (target, kget) ->
          notify (fun () -> Interfaces.Read_request { owner = fr.frame_owner; target });
          if is_dormant st target
          then Some { cfg_state = (add_reader st target fr.frame_owner);
                 cfg_control = (RunRhs (fr, (read_result fr target kget D.bottom), k)) }
          else (match Ranking.lookup st.ranking target with
                | Some _ ->
                  let st0 = observe st target in
                  if is_materialized st0 target
                  then let (p, value) = dirty_complete_get tf st0 fr target in
                       let (st1, fr1) = p in
                       Some { cfg_state = st1; cfg_control = (RunRhs (fr1,
                       (read_result fr1 target kget value), k)) }
                  else if rank_lt st0 fr.frame_owner target
                       then Some { cfg_state = st0; cfg_control =
                              (StartEpisode (target, (KAfterGet (fr, target,
                              kget, k)))) }
                       else let st1 = enqueue st0 target in
                            let (p, value) = complete_get st1 fr target in
                            let (st2, fr1) = p in
                            Some { cfg_state = st2; cfg_control = (RunRhs
                            (fr1, (read_result fr1 target kget value), k)) }
                | None ->
                  if (&&) (pure_bottom_rhs tf target)
                       (negb (is_materialized st target))
                  then let st1 = remember_dormant st target in
                       Some { cfg_state =
                       (add_reader st1 target fr.frame_owner); cfg_control =
                       (RunRhs (fr, (read_result fr target kget D.bottom), k)) }
                  else let st0 = observe st target in
                       if (&&) (negb (is_materialized st0 target))
                            (rank_lt st0 fr.frame_owner target)
                       then Some { cfg_state = st0; cfg_control =
                              (StartEpisode (target, (KAfterGet (fr, target,
                              kget, k)))) }
                       else let st1 =
                              if is_materialized st0 target
                              then st0
                              else enqueue st0 target
                            in
                            let (p, value) = complete_get st1 fr target in
                            let (st2, fr1) = p in
                            Some { cfg_state = st2; cfg_control = (RunRhs
                            (fr1, (read_result fr1 target kget value), k)) })
        | ConstraintSystem.Side (target, raw, next) ->
          notify (fun () -> Interfaces.Side { owner = fr.frame_owner; target; value = raw });
          let was_dormant = is_dormant st target in
          let st0 = observe st target in
          let (fr1, input) = record_side_input fr target raw in
          let (st1, changed) = write_side_contribution st0 fr1 target input in
          if was_dormant
          then Some (continue_side st1 fr1 target next k true)
          else if changed
               then Some
                      (continue_side (mark_side_dirty st1 target) fr1 target
                        next k true)
               else Some (continue_side st1 fr1 target next k false)
        | ConstraintSystem.Spawn (target, next) ->
          notify (fun () -> Interfaces.Spawn { owner = fr.frame_owner; target });
          if Features.defer_spawns
          then Some { cfg_state = (request_spawn st target); cfg_control =
                 (RunRhs (fr, next, k)) }
          else if is_dormant st target
               then Some { cfg_state = st; cfg_control = (RunRhs (fr, next,
                      k)) }
               else (match Ranking.lookup st.ranking target with
                     | Some _ ->
                       let st0 = observe st target in
                       if is_materialized st0 target
                       then Some { cfg_state = st0; cfg_control = (RunRhs
                              (fr, next, k)) }
                       else if rank_lt st0 fr.frame_owner target
                            then Some { cfg_state = st0; cfg_control =
                                   (StartEpisode (target, (KAfterSpawn (fr,
                                   next, k)))) }
                            else Some { cfg_state =
                                   (materialize (enqueue st0 target) target);
                                   cfg_control = (RunRhs (fr, next, k)) }
                     | None ->
                       if (&&) (pure_bottom_rhs tf target)
                            (negb (is_materialized st target))
                       then Some { cfg_state = (remember_dormant st target);
                              cfg_control = (RunRhs (fr, next, k)) }
                       else let st0 = observe st target in
                            if is_materialized st0 target
                            then Some { cfg_state = st0; cfg_control =
                                   (RunRhs (fr, next, k)) }
                            else if rank_lt st0 fr.frame_owner target
                                 then Some { cfg_state = st0; cfg_control =
                                        (StartEpisode (target, (KAfterSpawn
                                        (fr, next, k)))) }
                                 else Some { cfg_state =
                                        (materialize (enqueue st0 target)
                                          target);
                                        cfg_control = (RunRhs (fr, next, k)) }))
     | RunDead (fr, direct, pending, k) ->
       (match pending with
        | [] ->
          Some { cfg_state = (publish_targets st fr); cfg_control =
            (RunCommit (fr, direct, k)) }
        | target :: remaining ->
          if S.mem target fr.frame_current_targets
          then Some { cfg_state = st; cfg_control = (RunDead (fr, direct,
                 remaining, k)) }
          else let (st1, changed) =
                 write_side_contribution st fr target D.bottom
               in
               let st2 = if changed then mark_side_dirty st1 target else st1
               in
               Some (continue_dead st2 fr direct target remaining k changed))
     | RunCommit (fr, direct, k) ->
       let (st1, fr1) = set_value (flush_deferred st) fr direct in
       Some { cfg_state = st1; cfg_control = (RunDrain (fr1, k)) }
     | RunDrain (fr, k) ->
       (match queue_peek st.queue with
        | Some next ->
          if V.eq_dec next fr.frame_owner
          then (match queue_pop st.queue with
                | Some p ->
                  let (_, rest) = p in
                  let st1 =
                    clear_side_dirty (with_queue st rest) fr.frame_owner
                  in
                  evaluation_start fr.frame_owner;
                  Some { cfg_state = st1; cfg_control = (RunRhs
                  ((fresh_frame st1 fr.frame_owner fr.frame_phase),
                  (tf fr.frame_owner), k)) }
                | None -> None)
          else if rank_lt st fr.frame_owner next
               then (match queue_pop st.queue with
                     | Some p ->
                       let (_, rest) = p in
                       Some { cfg_state = (with_queue st rest); cfg_control =
                       (StartEpisode (next, (KDrain (fr, k)))) }
                     | None -> None)
               else Some { cfg_state =
                      (reset_registered_cells st fr.frame_owner);
                      cfg_control = (Return k) }
        | None ->
          Some { cfg_state = (reset_registered_cells st fr.frame_owner);
            cfg_control = (Return k) })
     | Return k ->
       (match k with
        | KLoop -> Some { cfg_state = st; cfg_control = RunLoop }
        | KSeedLoop remaining ->
          Some { cfg_state = st; cfg_control = (RunSeedLoop remaining) }
        | KAfterGet (fr, target, kget, k') ->
          let (p, value) = complete_get st fr target in
          let (st1, fr1) = p in
          Some { cfg_state = st1; cfg_control = (RunRhs (fr1, (read_result fr1 target kget value),
          k')) }
        | KAfterSide (fr, next, k') ->
          Some { cfg_state = st; cfg_control = (RunRhs (fr, next, k')) }
        | KAfterSpawn (fr, next, k') ->
          Some { cfg_state = st; cfg_control = (RunRhs (fr, next, k')) }
        | KDead (fr, direct, remaining, k') ->
          Some { cfg_state = st; cfg_control = (RunDead (fr, direct,
            remaining, k')) }
        | KDrain (fr, k') ->
          Some { cfg_state = st; cfg_control = (RunDrain (fr, k')) }))

    let rec run_fuel fuel tf c =
    (fun fO fS n -> if n=0 then fO () else fS (n-1))
      (fun _ -> c)
      (fun remaining ->
      match next_config tf c with
      | Some next -> run_fuel remaining tf next
      | None -> c)
      fuel

    let terminal_state c =
    match c.cfg_control with
    | RunLoop ->
      (match queue_peek c.cfg_state.queue with
       | Some _ -> None
       | None ->
         (match queue_peek c.cfg_state.deferred_wakes with
          | Some _ -> None
          | None ->
            (if Stdlib.Queue.is_empty c.cfg_state.pending_spawns
             then Some c.cfg_state else None)))
    | _ -> None

    let solve_fuel fuel tf initial =
    terminal_state (run_fuel fuel tf (initial_config initial))

    let solve_values_fuel fuel tf initial =
    match solve_fuel fuel tf initial with
    | Some final -> Some final.sigma
    | None -> None
 end

