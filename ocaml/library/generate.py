#!/usr/bin/env python3
"""Derive generic cores from unchanged generated callback adapters.

Only frontend plumbing changes here. Algorithm edits belong in the original
Rocq control / adapter templates. Every transformation checks its boundaries.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = '(* GENERATED by make regenerate; do not edit. See docs/third-party.md. *)\n'


def transform(source, variant, bitmap):
    def once(old, new):
        nonlocal source
        count = source.count(old)
        if count != 1:
            raise ValueError(f'{variant}: expected one {old!r}, found {count}')
        source = source.replace(old, new)

    def region(start, end, replacement):
        nonlocal source
        if source.count(start) != 1 or source.count(end) != 1:
            raise ValueError(f'{variant}: changed region {start!r} / {end!r}')
        a, b = source.index(start), source.index(end)
        if a >= b:
            raise ValueError(f'{variant}: reversed region')
        source = source[:a] + replacement + source[b:]

    if source.count('module Control = struct') != 1:
        raise ValueError(f'{variant}: missing extracted control')
    source = source[source.index('module Control = struct'):]
    once('    (Update : UPDATE) : DemandEqIncrSolver =\n'
         '  functor (Arg : IncrSolverArg)\n'
         '    (S : DemandEqConstrSys)\n'
         '    (VH : Hashtbl.S with type key = S.v) ->',
         '    (S : Core_common.SYSTEM)\n'
         '    (U : Interfaces.UPDATE with type variable = S.v and type value = S.d)\n'
         '    (VH : Core_common.TABLE with type key = S.v) =')
    once('    module U = Update (S)\n\n'
         '    type marshal = unit\n\n'
         '    let copy_marshal () = ()\n'
         '    let relift_marshal () = ()\n\n', '')
    region('    let trace_supported = true', '    type set =',
           '    type trace = unit\n'
           '    let create_trace () = ()\n'
           '    let[@inline always] trace_node _ _ _ = ()\n'
           '    let[@inline always] trace_queue _ _ _ = ()\n'
           '    let[@inline always] trace_evaluation _ _ = ()\n'
           '    let[@inline always] trace_value _ _ _ = ()\n\n')
    region('    module RankQueue = struct', '    type queue =',
           '    module RankQueue = struct\n' + bitmap + '\n    end\n\n')
    region('    let[@inline always] trace_get', '    let[@inline always] seed_started',
           '    let[@inline always] trace_get _ _ _ = ()\n'
           '    let[@inline always] trace_side _ _ _ = ()\n\n')
    region('    let finish_trace queue =', '    type state =',
           '    let[@inline always] finish_trace _ = ()\n\n')
    if variant != 'narrowing_fixed_point':
        region('      match state.queue.trace with', '    let solve xs roots _old_data =',
               '      ()\n\n')
    once('            incr SolverStats.evals', '            ()')
    once('      SolverStats.vars := !SolverStats.vars + VH.length state.sigma;\n', '')
    once('    let solve xs roots _old_data =', '    let solve xs roots =')
    once('      state.sigma, ()', '      state.sigma')
    once('\nmodule SLRTC = Make (Control)' +
         ('' if variant == 'simple' else ' (Features)'), '')
    if variant == 'restarting':
        once('The generated Goblint examples enable both.',
             'The internal example configuration enables both.')
    for forbidden in ('Goblint', 'Batteries', 'Yojson', 'SolverStats', 'marshal',
                      'IncrSolver', 'DemandEq', 'Sys.getenv', 'Slrtc_update'):
        if forbidden in source:
            raise ValueError(f'{variant}: leftover frontend reference {forbidden}')
    return HEADER + source


def main():
    output = ROOT / 'ocaml/library/generated'
    output.mkdir(exist_ok=True)
    bitmap = (ROOT / 'ocaml/runtime/rank_worklist_bitmap.ml').read_text()
    for variant in ('simple', 'restarting', 'narrowing_fixed_point'):
        source = (ROOT / f'ocaml/adapters/goblint/generated/slrtc_{variant}.ml').read_text()
        (output / f'core_{variant}.ml').write_text(transform(source, variant, bitmap))


if __name__ == '__main__':
    main()
