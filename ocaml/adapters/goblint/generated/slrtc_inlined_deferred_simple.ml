        mark_controlled frame.owner_info source_rank target_rank;
        let old_aggregate = target_info.side_aggregate in
        let cells =
          match target_info.side_cells with
          | Some cells -> cells
          | None ->
            let cells = VH.create 4 in
            target_info.side_cells <- Some cells;
            cells
        in
        let cell =
          try VH.find cells source with Not_found ->
            let fresh =
              {
                phase = U.initial_phase true target;
                contribution = bottom;
              }
            in
            VH.replace cells source fresh;
            fresh
        in
        let old_contribution = cell.contribution in
        let next_phase, next_contribution =
          side_update target cell.phase old_contribution input old_aggregate
        in
        cell.phase <- next_phase;
        cell.contribution <- next_contribution;
        let next_aggregate, aggregate_changed =
          if S.Dom.leq old_contribution next_contribution then
            if S.Dom.leq next_contribution old_aggregate
            then old_aggregate, false
            else S.Dom.join old_aggregate next_contribution, true
          else begin
            let next_aggregate = recompute_aggregate cells in
            next_aggregate,
              not (lattice_equal next_aggregate old_aggregate)
          end
        in
        if aggregate_changed then
          target_info.side_aggregate <- next_aggregate;
        if was_dormant then begin
          (* The dormant certificate says the direct RHS is exactly bottom,
              so publishing the aggregate completes the target without a
              redundant transfer evaluation. *)
          target_info.started <- true;
          materialize state target;
          if aggregate_changed then
            write_changed_value
              state target_rank target_info target next_aggregate
        end else if aggregate_changed then begin
          queue_note_side_change state.queue source_rank target_rank;
          if source_rank < target_rank
             && not (VH.mem state.sigma target)
          then
            solve_episode target
          else
            enqueue state target
        end

      and spawn frame target =
        if Features.defer_spawns then defer_spawn target
        else spawn_immediate frame target

      and spawn_immediate frame target =
        let owner_rank = frame.owner_rank in
        match VH.find_option state.queue.ranks target with
        | None when not (VH.mem state.sigma target) ->
          ignore (request_unranked target)
        | possible_rank ->
          let target_rank =
            match possible_rank with
            | Some target_rank -> target_rank
            | None -> let target_rank, _, _ = activate_rank state target in target_rank
          in
          if not (VH.mem state.sigma target) then
            if owner_rank < target_rank then
              solve_episode target
            else begin
              enqueue state target;
              materialize state target
            end
      in

      let is_started variable =
        match VH.find_option state.dormant_bottom variable with
        | Some _ -> true
        | None ->
          match VH.find_option state.queue.ranks variable with
          | None -> false
          | Some variable_rank ->
            (Dynarray.get state.queue.infos variable_rank).started
      in
      let solve_requested variable =
        match VH.find_option state.queue.ranks variable with
        | Some _ -> solve_episode variable
        | None when VH.mem state.sigma variable -> solve_episode variable
        | None -> ignore (request_unranked variable)
      in

      List.iter
        (fun (variable, input) ->
          let start = S.Dom.join (start_value state variable) input in
          VH.replace state.starts variable start;
          VH.replace state.sigma variable start)
        xs;
      begin match
        Control.solve_seeds_with_fuel Stdlib.max_int
          is_started
          (fun () -> queue_pop state.queue)
          solve_requested
          (roots @ List.map fst xs)
      with
      | Control.SeedsSolved _ -> ()
      | Control.SeedsOutOfFuel ->
        failwith "Deferred Simple: exhausted max_int seed fuel"
      end;
      let rec drain_spawns () =
        match Stdlib.Queue.take_opt pending_fifo with
        | None -> ()
        | Some target ->
          begin match Control.solve_seeds_with_fuel Stdlib.max_int
            is_started (fun () -> queue_pop state.queue) solve_requested [target] with
          | Control.SeedsSolved _ -> ()
          | Control.SeedsOutOfFuel -> failwith "Deferred Simple: exhausted spawn fuel"
          end;
          drain_spawns ()
      in
      drain_spawns ();
      if dormant_stats_enabled then
        Stdlib.Printf.eprintf
          "%s probes=%d dormant=%d effectful=%d hits=%d promotions=%d remaining=%d\n%!"
          SidePolicy.stats_name !probes !dormant_created
          !effectful_promotions !dormant_hits
          !dormant_promotions (VH.length state.dormant_bottom);
      SolverStats.vars := !SolverStats.vars + VH.length state.sigma;
      state.sigma, ()
  end
